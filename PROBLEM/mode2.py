# Problem 2: Student Registration 
# A college is collecting basic information from newly admitted students.
# Write a program that asks the student for their name, age, and course of study. 
# After collecting the information, display all the details in a neat and readable format.

# Ask for user details :
name = input("Enter your name: ")
age = input("Enter your age: ")
course = input("Enter your course of study: ")

# Disply the collected information
print("\n-------Student Information--------")
print(f"Name   :{name}")
print(f"Age    :{age}")
print(f"Course :{course}")
print("------------------------------------")
